"""Generate range-reduction tables for Cox's float and double exponentials.

The table contains rounded powers of two. The two polynomial coefficients and
range-reduction constant preserve the Apple silicon reference's float32 exp
rounding; using a more accurate exp(double) and casting gives different results.
The double table stores floored powers of two with logarithmic corrections.
"""
from pathlib import Path
from decimal import Decimal, localcontext
import argparse
import math
import struct


def float32(value):
    return struct.unpack("<f", struct.pack("<f", float(value)))[0]


def pair(value):
    high = float32(value)
    low = float32(value - high)
    return f"float2({high.hex()}f, {low.hex()}f)"


def generate():
    with localcontext() as context:
        context.prec = 90
        table = [float((Decimal(2).ln() * Decimal(i) / 128).exp()) for i in range(128)]
    text = "// Generated by tools/generate_cox_constants.py; do not edit by hand.\n"
    text += "constant float2 kCoxExpTable[128] = {\n"
    text += ",\n".join("  " + pair(value) for value in table) + "\n};\n"
    for name, value in [("Inv", "0x1.71547652b82fep+7"),
                        ("First", "0x1.62e4453e10daep-8"),
                        ("Second", "0x1.ebfbdff30d656p-17")]:
        text += f"constant float2 kCoxExp{name} = {pair(float.fromhex(value))};\n"
    # The double routine floors each power of two and stores the logarithmic
    # residual. Integer encodings preserve every coefficient and table bit.
    with localcontext() as context:
        context.prec = 100
        log2 = Decimal(2).ln()
        inverse = Decimal(128) / log2
        inv_high = float(inverse)
        inv_low = float(inverse - Decimal(inv_high))
        double_table = []
        for i in range(128):
            exact = (log2 * Decimal(i) / 128).exp()
            high = float(exact)
            if Decimal(high) > exact:
                high = math.nextafter(high, 0)
            low = float(Decimal(i) - Decimal(128) * Decimal(high).ln() / log2)
            double_table.append((high, low))
    coefficients = [inv_high, inv_low, *map(float.fromhex, [
        "0x1.ef1584af17ecdp+9", "-0x1.13b4d4879e55ep+6", "0x1.4ffde7cc02cf4p+18",
        "0x1.8b31b87eb8904p+18", "0x1.5e52272e0eaecp-45"])]
    def bits(value):
        return hex(struct.unpack("<Q", struct.pack("<d", value))[0]) + "ul"
    text += "constant ulong kCoxDoubleCoefficients[7] = {" + ", ".join(map(bits, coefficients)) + "};\n"
    text += "constant ulong2 kCoxDoubleTable[128] = {\n"
    text += ",\n".join(f"  ulong2({bits(a)}, {bits(b)})" for a, b in double_table) + "\n};\n"
    return text


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    path = Path(__file__).resolve().parents[1] / "kernels/cox_constants.metal.h"
    expected = generate()
    if args.check:
        assert path.read_text() == expected, f"Regenerate {path}"
    else:
        path.write_text(expected)
